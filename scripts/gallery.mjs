// Builds the examples gallery, docs/gallery.md and its pictures in docs/gallery/, from
// conformance cases. Each picture is the case's reference output.svg drawn with the bundled
// fonts, so the gallery always shows exactly what the reference renderer draws.
//
//   node scripts/gallery.mjs           write the gallery
//   node scripts/gallery.mjs --check   fail if the gallery is out of date (used in CI)
//
// Needs the packages built first (pnpm run build). To change what the gallery shows, edit
// SECTIONS below and run it again.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const cases = join(repo, 'conformance', 'cases');
const outDir = join(repo, 'docs', 'gallery');
const page = join(repo, 'docs', 'gallery.md');

/**
 * The gallery, in order. Each section shows one or more conformance cases; several cases are
 * shown side by side.
 * @type {{ title: string, text: string, cases: { name: string, caption?: string }[] }[]}
 */
const SECTIONS = [
  {
    title: 'Analytics dashboard',
    text: 'A desktop screen with a sidebar, a row of cards, a chart placeholder and a table.',
    cases: [{ name: 'example-18-1-analytics-dashboard' }],
  },
  {
    title: 'Data table with filters',
    text: 'A table with search and filters, a variant for "no results", and a drawer that a button opens. Variants are drawn below their screen, and an overlay that a link opens gets its own frame.',
    cases: [{ name: 'example-18-4-data-table-with-filters' }],
  },
  {
    title: 'Product page with a custom theme',
    text: 'A product page whose source defines its own theme, and a cart drawer opened from two places.',
    cases: [{ name: 'example-18-5-e-commerce-product-page' }],
  },
  {
    title: 'Document editor',
    text: 'A three-column editor with an outline, the document and comments, and a share dialog.',
    cases: [{ name: 'example-18-7-document-editor' }],
  },
  {
    title: 'Themes',
    text: 'The same source in three built-in themes, and in a theme the host app supplies.',
    cases: [
      { name: 'theme-paper', caption: 'paper' },
      { name: 'theme-ink', caption: 'ink' },
      { name: 'theme-blueprint', caption: 'blueprint' },
      { name: 'theme-host', caption: 'a host theme' },
    ],
  },
  {
    title: 'A theme of your own',
    text: 'The specimen for a theme defined in the source: every colour token, the type scale and the common components.',
    cases: [{ name: 'specimen-block' }],
  },
];

const { svgToPng } = await import(join(repo, 'packages', 'png', 'dist', 'index.js'));

/** @type {Map<string, Buffer | string>} */
const files = new Map();
const lines = [
  '<!-- Generated by scripts/gallery.mjs from the conformance cases. Edit SECTIONS there, not this file. -->',
  '',
  '# Examples gallery',
  '',
  'Pictures drawn by the reference renderer from sources in the [conformance suite](../conformance), each with its source. They are regenerated from the cases, and CI checks they are up to date.',
  '',
];
for (const section of SECTIONS) {
  lines.push(`## ${section.title}`, '', section.text, '');
  const pictures = section.cases.map((c) => {
    const svg = readFileSync(join(cases, c.name, 'output.svg'), 'utf8');
    files.set(`${c.name}.png`, Buffer.from(svgToPng(svg)));
    return `![${c.caption ?? section.title}](gallery/${c.name}.png)`;
  });
  if (pictures.length === 1) {
    lines.push(pictures[0] ?? '', '');
  } else {
    lines.push(`| ${section.cases.map((c) => c.caption ?? c.name).join(' | ')} |`);
    lines.push(`| ${section.cases.map(() => '---').join(' | ')} |`);
    lines.push(`| ${pictures.join(' | ')} |`, '');
  }
  for (const c of section.cases) {
    const source = readFileSync(join(cases, c.name, 'input.wirelith'), 'utf8');
    const options = existsSync(join(cases, c.name, 'options.json'));
    const label = c.caption ? `Source (${c.caption})` : 'Source';
    lines.push(
      '<details>',
      `<summary>${label}</summary>`,
      '',
      '```wirelith',
      source.trimEnd(),
      '```',
      '',
      `From [\`conformance/cases/${c.name}\`](../conformance/cases/${c.name})${options ? ', drawn with the render options in its `options.json`' : ''}.`,
      '',
      '</details>',
      '',
    );
  }
}
const markdown = `${lines.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  const stale = [];
  if (!existsSync(page) || readFileSync(page, 'utf8') !== markdown) stale.push('docs/gallery.md');
  for (const [name, bytes] of files) {
    const path = join(outDir, name);
    if (!existsSync(path) || !readFileSync(path).equals(/** @type {Buffer} */ (bytes)))
      stale.push(`docs/gallery/${name}`);
  }
  if (existsSync(outDir)) {
    for (const name of readdirSync(outDir))
      if (!files.has(name)) stale.push(`docs/gallery/${name} (not in the gallery)`);
  }
  if (stale.length > 0) {
    console.error(`gallery: out of date: ${stale.join(', ')}. Run: node scripts/gallery.mjs`);
    process.exit(1);
  }
  console.log(`gallery: up to date (${files.size} pictures).`);
} else {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const [name, bytes] of files) writeFileSync(join(outDir, name), bytes);
  writeFileSync(page, markdown);
  console.log(`gallery: wrote docs/gallery.md and ${files.size} pictures.`);
}
