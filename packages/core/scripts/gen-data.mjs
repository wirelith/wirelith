// Compiles the specification's data (spec/data) into compact TypeScript modules that ship
// inside @wirelith/core, which reads no files at runtime.
//
//   node packages/core/scripts/gen-data.mjs           write src/data/*.ts
//   node packages/core/scripts/gen-data.mjs --check   fail if they are out of date
//
// Font tables keep only the advances that differ from the table's default: a character with
// the default advance measures the same whether or not it is listed.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SPEC = 'spec/data';
const OUT = 'packages/core/src/data';
const HEADER =
  '// SPDX-License-Identifier: MIT\n\n// Generated by packages/core/scripts/gen-data.mjs from the specification. Do not edit.\n\n';

function fonts() {
  /** @type {Record<string, unknown>} */
  const tables = {};
  for (const f of readdirSync(join(SPEC, 'fonts')).sort()) {
    const t = JSON.parse(readFileSync(join(SPEC, 'fonts', f), 'utf8'));
    /** @type {[number, number][]} */
    const pairs = [];
    for (const [ch, adv] of Object.entries(t.advances)) {
      const cp = /** @type {number} */ (ch.codePointAt(0));
      if (adv !== t.default) pairs.push([cp, /** @type {number} */ (adv)]);
    }
    pairs.sort((a, b) => a[0] - b[0]);
    // Encoded as "codepoint:advance" pairs in base 36, separated by spaces.
    const adv = pairs.map(([cp, a]) => `${cp.toString(36)}:${a.toString(36)}`).join(' ');
    tables[`${t.font}-${t.weight}`] = [t.unitsPerEm, t.ascent, t.descent, t.default, adv];
  }
  return `${HEADER}/** font-weight -> [unitsPerEm, ascent, descent, default advance, encoded advances] */\nexport const FONT_TABLES: Record<string, [number, number, number, number, string]> = ${JSON.stringify(tables)};\n`;
}

function icons() {
  const d = JSON.parse(readFileSync(join(SPEC, 'icons.json'), 'utf8'));
  return `${HEADER}/** Icon name -> drawing name. */\nexport const ICON_NAMES: Record<string, string> = ${JSON.stringify(d.names)};\n\n/** Drawing name -> elements, in 24 x 24 icon units. */\nexport const ICON_DRAWINGS: Record<string, [string, Record<string, string>][]> = ${JSON.stringify(d.drawings)};\n`;
}

function aiSpec() {
  const text = readFileSync('spec/ai-spec.md', 'utf8');
  return `${HEADER}/** The one-page description of Wirelith for AI agents (spec/ai-spec.md). */\nexport const AI_SPEC: string = ${JSON.stringify(text)};\n`;
}

const files = { 'fonts.ts': fonts(), 'icons.ts': icons(), 'ai-spec.ts': aiSpec() };
const check = process.argv.includes('--check');
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const path = join(OUT, name);
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {}
    if (current !== text) {
      console.error(`${path} is out of date; run node packages/core/scripts/gen-data.mjs`);
      stale++;
    }
  } else {
    writeFileSync(path, text);
  }
}
if (stale > 0) process.exit(1);
console.log(check ? 'core data: up to date.' : `core data: written to ${OUT}.`);
